import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const cli = resolve('node_modules', 'supabase', 'dist', 'supabase.js')
const destination = resolve(
  'src',
  'shared',
  'api',
  'supabase',
  'database.types.ts',
)

const generatedTypes = execFileSync(
  process.execPath,
  [
    cli,
    'gen',
    'types',
    '--lang',
    'typescript',
    '--local',
    '--schema',
    'public',
  ],
  { encoding: 'utf8' },
)

const generatedFile = `// Generated by Supabase CLI — do not edit manually.\n${generatedTypes}`

if (process.argv.includes('--check')) {
  const currentFile = readFileSync(destination, 'utf8')
  if (currentFile !== generatedFile) {
    throw new Error(
      'Generated database types have drifted. Run npm run db:types.',
    )
  }
  console.log('Generated database types are up to date.')
  process.exit(0)
}

writeFileSync(
  destination,
  generatedFile,
  'utf8',
)
